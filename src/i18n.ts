const dicts: Record<Language, Dict> = { en, zh }
// Content translations (case prose, marker details, previews, source labels)
// live in i18n-extra.ts; English falls back to the canonical source string.
const fixtureDicts: Record<Language, Dict> = { en: fixtureEn, zh: { ...extraZh, ...fixtureZh } }

export function t(key: string, lang: Language = 'en', params?: Record<string, string | number>): string {
  let str = dicts[lang]?.[key] || dicts.en[key] || key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return str
}

export function useT() {
  const { lang } = useI18n()
  return (key: string, params?: Record<string, string | number>) => t(key, lang, params)
}

/** Translate fixture content (thoughts, tool summaries, trap descriptions, etc.) */
export function fixture(englishText: string, lang: Language = 'en'): string {
  return fixtureDicts[lang]?.[englishText] ?? englishText
}

/** Labels created in Chinese must also display in English after a language switch.
 * Keep the stored label and the Chinese rendering unchanged.
 */
export function variantLabel(label: string, lang: Language): string {
  return lang === 'en' ? label.replace(/^配置 (\d+)$/, 'Variant $1') : label
}

export function useVariantLabel() {
  const { lang } = useI18n()
  return (label: string) => variantLabel(label, lang)
}

/** React hook: returns a fixture translation function bound to the current language */
export function useFixture() {
  const { lang } = useI18n()
  return (englishText: string) => fixture(englishText, lang)
}
